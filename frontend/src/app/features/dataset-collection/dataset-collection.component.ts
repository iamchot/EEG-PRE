import { CommonModule } from '@angular/common';
import { Component, OnInit, signal } from '@angular/core';
import { FormsModule } from '@angular/forms';
import { RouterLink } from '@angular/router';

import {
  CollectionOverview,
  CollectionSession,
  DatasetCollectionService,
  DatasetParticipant,
  EmotionQuadrant,
  EmotionStimulus,
  StimulusApprovalState,
} from '../../core/services/dataset-collection.service';

type CollectionTab = 'overview' | 'participants' | 'stimuli' | 'sessions';

@Component({
  selector: 'app-dataset-collection',
  standalone: true,
  imports: [CommonModule, FormsModule, RouterLink],
  template: `
    <main class="collection-shell">
      <header class="page-header">
        <div>
          <a routerLink="/admin" class="back-link">← Admin dashboard</a>
          <h1>EEG Dataset Collection</h1>
          <p>Prepare pseudonymous participants, stimuli, and collection sessions.</p>
        </div>
        <aside class="notice" data-testid="non-medical-notice">
          Entertainment and prototype research only — not medical diagnosis or treatment.
        </aside>
      </header>

      <nav class="tabs" role="tablist" aria-label="Dataset collection sections">
        @for (tab of tabs; track tab.key) {
          <button type="button" role="tab" [attr.aria-selected]="activeTab() === tab.key"
            [id]="'collection-tab-' + tab.key" [attr.aria-controls]="'collection-panel-' + tab.key"
            [tabIndex]="activeTab() === tab.key ? 0 : -1" [class.active]="activeTab() === tab.key"
            (click)="switchTab(tab.key)" (keydown)="onTabKeydown($event, tab.key)">{{ tab.label }}</button>
        }
      </nav>

      @if (error()) { <div class="error" role="alert">{{ error() }}</div> }

      @if (activeTab() === 'overview') {
        <section id="collection-panel-overview" aria-labelledby="collection-tab-overview" class="panel" role="tabpanel">
          <h2>Collection overview</h2>
          @if (overviewLoading()) {
            <p role="status">Loading overview…</p>
          } @else {
            @if (overview(); as stats) {
              <div class="stat-grid">
                <article class="stat-card"><span>Participants</span><strong>{{ stats.participants }}</strong></article>
                <article class="stat-card"><span>Sessions</span><strong>{{ stats.sessions }}</strong></article>
                <article class="stat-card"><span>Trials</span><strong>{{ stats.trials }}</strong></article>
                <article class="stat-card"><span>Pending review</span><strong>{{ stats.review_counts.pending }}</strong></article>
              </div>
            } @else { <p>Overview data is unavailable.</p> }
          }
        </section>
      }

      @if (activeTab() === 'participants') {
        <section id="collection-panel-participants" aria-labelledby="collection-tab-participants" class="split" role="tabpanel">
          <form id="participant-form" class="panel form-card" (ngSubmit)="registerParticipant()">
            <h2>Register participant</h2>
            <p>A pseudonymous participant code such as P001 is generated by the server.</p>
            <label class="check-row" for="consent-confirmed">
              <input id="consent-confirmed" name="consent_confirmed" type="checkbox" required
                [(ngModel)]="consentConfirmed">
              <span>Consent has been confirmed and documented.</span>
            </label>
            <button id="register-participant" class="primary" type="submit"
              [disabled]="!consentConfirmed || participantSubmitting()">
              {{ participantSubmitting() ? 'Registering…' : 'Register participant' }}
            </button>
          </form>
          <section class="panel"><h2>Participants</h2>
            <div class="list">@if (participantsLoading()) { <p role="status">Loading participants…</p> } @else { @for (item of participants(); track item.id) {
              <div class="list-row"><strong>{{ item.participant_code }}</strong><span class="badge">{{ item.state }}</span></div>
            } @empty { <p>No participants registered.</p> } }</div>
          </section>
        </section>
      }

      @if (activeTab() === 'stimuli') {
        <section id="collection-panel-stimuli" aria-labelledby="collection-tab-stimuli" class="split" role="tabpanel">
          <form class="panel form-card" (ngSubmit)="registerStimulus()">
            <h2>Register stimulus</h2>
            <label>Title<input name="title" required [(ngModel)]="stimulus.title"></label>
            <label>Media file reference<input name="file_path" required [(ngModel)]="stimulus.file_path"></label>
            <label>SHA-256 checksum<input name="checksum" required minlength="64" maxlength="64" [(ngModel)]="stimulus.checksum"></label>
            <label>Duration (45–60 seconds)<input name="duration" type="number" min="45" max="60" required [(ngModel)]="stimulus.duration_seconds"></label>
            <label>Target quadrant<select id="target-quadrant" name="quadrant" required [(ngModel)]="stimulus.target_quadrant">
              @for (quadrant of quadrants; track quadrant) { <option [value]="quadrant">{{ quadrant }}</option> }
            </select></label>
            <label>Approval state<select name="approval" [(ngModel)]="stimulus.approval_state"><option value="draft">draft</option><option value="approved">approved</option><option value="retired">retired</option></select></label>
            <label>Stimulus set version<input name="version" required [(ngModel)]="stimulus.stimulus_set_version"></label>
            <button class="primary" type="submit" [disabled]="stimulusSubmitting() || !isStimulusReady()">{{ stimulusSubmitting() ? 'Registering…' : 'Register stimulus' }}</button>
          </form>
          <section class="panel"><h2>Stimuli</h2><div class="list">@if (stimuliLoading()) { <p role="status">Loading stimuli…</p> } @else { @for (item of stimuli(); track item.id) {
            <div class="list-row"><div><strong>{{ item.title }}</strong><small>{{ item.target_quadrant }} · {{ item.duration_seconds }}s</small></div><span class="badge">{{ item.approval_state }}</span></div>
          } @empty { <p>No stimuli registered.</p> } }</div></section>
        </section>
      }

      @if (activeTab() === 'sessions') {
        <section id="collection-panel-sessions" aria-labelledby="collection-tab-sessions" class="split" role="tabpanel">
          <form class="panel form-card" (ngSubmit)="createSession()">
            <h2>Create collection session</h2>
            <label>Active participant<select name="participant" required [(ngModel)]="sessionParticipantId">
              <option [ngValue]="null">Select a participant</option>
              @for (item of activeParticipants(); track item.id) { <option [ngValue]="item.id">{{ item.participant_code }}</option> }
            </select></label>
            <label>Device ID (optional)<input name="device_id" [(ngModel)]="deviceId"></label>
            <label>Device label (optional)<input name="device_name" [(ngModel)]="deviceName"></label>
            <button id="create-session" class="primary" type="submit" [disabled]="!hasActiveParticipant() || sessionSubmitting()">{{ sessionSubmitting() ? 'Creating…' : 'Create session' }}</button>
          </form>
          <section class="panel"><h2>Sessions</h2><div class="list">@if (sessionsLoading()) { <p role="status">Loading sessions…</p> } @else { @for (item of sessions(); track item.id) {
            <div class="list-row"><strong>Session {{ item.id }}</strong><span class="badge">{{ item.state }}</span></div>
          } @empty { <p>No sessions created.</p> } }</div></section>
        </section>
      }
    </main>
  `,
  styleUrl: './dataset-collection.component.css',
})
export class DatasetCollectionComponent implements OnInit {
  readonly tabs: { key: CollectionTab; label: string }[] = [
    { key: 'overview', label: 'Overview' }, { key: 'participants', label: 'Participants' },
    { key: 'stimuli', label: 'Stimuli' }, { key: 'sessions', label: 'Sessions' },
  ];
  readonly quadrants: EmotionQuadrant[] = ['positive_low', 'positive_high', 'negative_low', 'negative_high'];
  readonly activeTab = signal<CollectionTab>('overview');
  readonly overview = signal<CollectionOverview | null>(null);
  readonly overviewLoading = signal(true);
  readonly participants = signal<DatasetParticipant[]>([]);
  readonly stimuli = signal<EmotionStimulus[]>([]);
  readonly sessions = signal<CollectionSession[]>([]);
  readonly participantsLoading = signal(true);
  readonly stimuliLoading = signal(true);
  readonly sessionsLoading = signal(true);
  readonly error = signal('');
  readonly participantSubmitting = signal(false);
  readonly stimulusSubmitting = signal(false);
  readonly sessionSubmitting = signal(false);

  consentConfirmed = false;
  stimulus = { title: '', file_path: '', checksum: '', duration_seconds: 45, target_quadrant: 'positive_low' as EmotionQuadrant, approval_state: 'draft' as StimulusApprovalState, stimulus_set_version: 'v1' };
  sessionParticipantId: number | null = null;
  deviceId = '';
  deviceName = '';

  constructor(private readonly api: DatasetCollectionService) {}

  ngOnInit(): void { this.loadOverview(); this.loadParticipants(); this.loadStimuli(); this.loadSessions(); }
  switchTab(tab: CollectionTab): void { this.activeTab.set(tab); }
  onTabKeydown(event: KeyboardEvent, current: CollectionTab): void {
    const index = this.tabs.findIndex((tab) => tab.key === current);
    let next = index;
    if (event.key === 'ArrowRight') next = (index + 1) % this.tabs.length;
    else if (event.key === 'ArrowLeft') next = (index - 1 + this.tabs.length) % this.tabs.length;
    else if (event.key === 'Home') next = 0;
    else if (event.key === 'End') next = this.tabs.length - 1;
    else return;
    event.preventDefault();
    const key = this.tabs[next].key;
    this.switchTab(key);
    document.getElementById(`collection-tab-${key}`)?.focus();
  }
  activeParticipants(): DatasetParticipant[] { return this.participants().filter((item) => item.state === 'active'); }
  hasActiveParticipant(): boolean { return this.sessionParticipantId !== null && this.activeParticipants().some((item) => item.id === this.sessionParticipantId); }
  isStimulusDurationValid(): boolean { return this.stimulus.duration_seconds >= 45 && this.stimulus.duration_seconds <= 60; }
  isStimulusReady(): boolean { return !!(this.stimulus.title.trim() && this.stimulus.file_path.trim() && this.stimulus.checksum.length === 64 && this.stimulus.stimulus_set_version.trim() && this.isStimulusDurationValid()); }

  registerParticipant(): void {
    if (!this.consentConfirmed || this.participantSubmitting()) return;
    this.participantSubmitting.set(true); this.error.set('');
    this.api.createParticipant({ consent_confirmed_at: new Date().toISOString() }).subscribe({
      next: (item) => { this.participants.update((items) => [item, ...items]); this.consentConfirmed = false; this.participantSubmitting.set(false); },
      error: (err) => this.fail(err, this.participantSubmitting),
    });
  }

  registerStimulus(): void {
    if (!this.isStimulusReady() || this.stimulusSubmitting()) return;
    this.stimulusSubmitting.set(true); this.error.set('');
    this.api.createStimulus({ ...this.stimulus }).subscribe({
      next: (item) => { this.stimuli.update((items) => [item, ...items]); this.stimulusSubmitting.set(false); },
      error: (err) => this.fail(err, this.stimulusSubmitting),
    });
  }

  createSession(): void {
    if (!this.hasActiveParticipant() || this.sessionParticipantId === null || this.sessionSubmitting()) return;
    this.sessionSubmitting.set(true); this.error.set('');
    this.api.createSession({ participant_id: this.sessionParticipantId, device_id: this.deviceId.trim() || null, device_name: this.deviceName.trim() || null }).subscribe({
      next: (item) => { this.sessions.update((items) => [item, ...items]); this.sessionSubmitting.set(false); },
      error: (err) => this.fail(err, this.sessionSubmitting),
    });
  }

  private loadOverview(): void {
    this.overviewLoading.set(true);
    this.api.getOverview().subscribe({
      next: (value) => { this.overview.set(value); this.overviewLoading.set(false); },
      error: (err) => { this.overviewLoading.set(false); this.fail(err); },
    });
  }
  private loadParticipants(): void { this.participantsLoading.set(true); this.api.listParticipants().subscribe({ next: (value) => { this.participants.set(value.items); this.participantsLoading.set(false); }, error: (err) => { this.participantsLoading.set(false); this.fail(err); } }); }
  private loadStimuli(): void { this.stimuliLoading.set(true); this.api.listStimuli().subscribe({ next: (value) => { this.stimuli.set(value.items); this.stimuliLoading.set(false); }, error: (err) => { this.stimuliLoading.set(false); this.fail(err); } }); }
  private loadSessions(): void { this.sessionsLoading.set(true); this.api.listSessions().subscribe({ next: (value) => { this.sessions.set(value.items); this.sessionsLoading.set(false); }, error: (err) => { this.sessionsLoading.set(false); this.fail(err); } }); }
  private fail(err: unknown, busy?: { set(value: boolean): void }): void {
    busy?.set(false);
    const response = err as { error?: { detail?: string } | string; message?: string };
    this.error.set(typeof response.error === 'string' ? response.error : response.error?.detail ?? response.message ?? 'The request could not be completed.');
  }
}
